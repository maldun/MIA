"""Generate the integration step tests of every node that has a scenario (specs/mia/integration-drafts/tests/integration/<node>/scenario.py).

Usage: python3 -I tools/gen_integration_drafts.py <repository root>
Reads the `integration` order and the interface providers from specs/mia/decomposition.yaml and writes step_00 (all parts as mocks) to step_NN
(the first NN children real) next to each scenario. The scenarios are written by hand and reviewed by the owner; the steps are generated, so
re-running changes nothing unless the decomposition changed. Install with tools/install_integration_drafts.sh."""
import pathlib
import sys

import yaml

TEMPLATE = '''"""Step {step} of {node}: {what}. Generated by tools/gen_integration_drafts.py from decomposition.yaml (protected after installing).
The scenario is in ../scenario.py; the parts integrated so far are real, all others are mocks. Run with: python tests/integration/{node}/step_{step:02d}/test_step.py"""
import os
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "helpers"))

from integration import need, ports  # noqa: E402
from markers import mark             # noqa: E402
import scenario                      # noqa: E402

REAL_NODES = {nodes}
REAL_INTERFACES = {interfaces}


class Step{step:02d}(unittest.TestCase):
    @mark.req(*scenario.MARKS[{step}])
    def test_scenario_{step:02d}(self):
        """{what}"""
        need(REAL_NODES)
        scenario.run(ports(REAL_INTERFACES), self)


if __name__ == "__main__":
    unittest.main()
'''


def main(root):
    root = pathlib.Path(root)
    record = yaml.safe_load((root / "specs/mia/decomposition.yaml").read_text(encoding="utf-8"))["decomposition"]
    providers = {i["id"]: i["provider"] for i in record["interfaces"]}
    nodes = {n["id"]: n for n in record["nodes"]}
    python_ifs = [i for i in providers if i not in ("IF-111", "IF-112") and not providers[i].startswith("ext:")]
    base = root / "specs/mia/integration-drafts/tests/integration"
    for entry in record["integration"]:
        node = entry["node"]
        if not (base / node / "scenario.py").exists():
            print("no scenario for", node)
            continue
        real = []
        for step, item in enumerate([None] + entry["order"]):
            if item:
                real.append(item["child"])
            # an interface is real when its provider is a real child (or below one), or when the node itself provides it and the boundary hands it to a real child
            handed = {b["interface"] for b in nodes[node].get("boundary", []) if b["role"] == "provides" and b["child"] in real}
            owned = tuple(i for i in python_ifs if i in handed or any(providers[i] == c or providers[i].startswith(c + ".") for c in real))
            what = "all parts as mocks (the skeleton)" if item is None else "%s real" % item["child"]
            folder = base / node / ("step_%02d" % step)
            folder.mkdir(parents=True, exist_ok=True)
            (folder / "test_step.py").write_text(TEMPLATE.format(step=step, node=node, what=what, nodes=repr(tuple(real)), interfaces=repr(owned)), encoding="utf-8")
            print("%s step_%02d  real nodes %s  real interfaces %s" % (node, step, tuple(real), owned))


main(sys.argv[1])
